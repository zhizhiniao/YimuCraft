// Generates src/ae-panel/ae-state.jsx from src/adobe-host.jsx.
//
// After Effects runs this file from its Scripts/Startup folder, so it lives in
// the same instance as the user's project and can publish live project state on a
// timer. The app reads that file instead of starting a throwaway AE instance
// (`AfterFX -r`), which can never see an open project.
const fs = require('fs');
const path = require('path');

const host = fs.readFileSync(path.join(__dirname, '..', 'src', 'adobe-host.jsx'), 'utf8');

function extract(startMarker) {
  const start = host.indexOf(startMarker);
  if (start < 0) throw new Error('Missing ' + startMarker + ' in adobe-host.jsx');
  let depth = 0;
  let i = host.indexOf('{', start);
  const bodyStart = i;
  for (; i < host.length; i++) {
    if (host[i] === '{') depth++;
    else if (host[i] === '}') {
      depth--;
      if (depth === 0) return host.slice(start, i + 1);
    }
  }
  throw new Error('Unbalanced braces for ' + startMarker);
}

const helpers = ['function quote(', 'function json(', 'function mkdir(', 'function same(', 'function projectInfo(']
  .map(extract)
  .join('\n  ');

const output = `// GENERATED by scripts/build-ae-state.cjs from src/adobe-host.jsx - do not edit.
// Installed into After Effects "Scripts/Startup" so the live instance publishes
// its project state for the YimuCraft desktop app.
(function () {
  ${helpers}

  function yimuCraftStateFolder() {
    var folder = new Folder(Folder.myDocuments.fsName + '/YimuCraft');
    if (!folder.exists) mkdir(folder);
    return folder;
  }

  function yimuCraftPublish() {
    try {
      if (typeof app === 'undefined' || !app.project) return;
      var state = projectInfo();
      state.ts = (new Date()).getTime();
      var folder = yimuCraftStateFolder();
      var target = new File(folder.fsName + '/ae-state.json');
      var temp = new File(folder.fsName + '/ae-state.json.tmp');
      temp.encoding = 'UTF-8';
      if (!temp.open('w')) return;
      temp.write(json(state));
      temp.close();
      if (target.exists) target.remove();
      temp.rename('ae-state.json');
    } catch (error) {}
  }

  // Serve the desktop app's queued requests in this same (live) instance, so the
  // app can import/collect against the project the user actually has open.
  function yimuCraftServe() {
    try {
      var rendezvous = new File(yimuCraftStateFolder().fsName + '/ae-panel.json');
      if (!rendezvous.exists) return;
      // Only serve requests the app has just announced; stale ones left by an
      // earlier crash could open modal dialogs during startup.
      if ((new Date()).getTime() - rendezvous.modified.getTime() > 60000) return;
      if (!rendezvous.open('r')) return;
      var text = rendezvous.read();
      rendezvous.close();
      var info = null;
      try { info = eval('(' + text + ')'); } catch (parseError) { return; }
      if (!info || !info.directory) return;
      var folder = new Folder(info.directory);
      if (!folder.exists) return;
      var files = folder.getFiles('*.jsx');
      var now = (new Date()).getTime();
      for (var i = 0; i < files.length; i++) {
        var file = files[i];
        var id = file.name.replace(/\.jsx$/i, '');
        var receipt = new File(folder.fsName + '/' + id + '.json');
        if (receipt.exists) continue;
        if (now - file.modified.getTime() > 120000) continue;
        try { $.evalFile(file); } catch (error) { $.writeln('YimuCraft request failed: ' + error); }
      }
    } catch (serveError) {}
  }

  function yimuCraftTick() {
    try { yimuCraftPublish(); } catch (publishError) {}
    try { yimuCraftServe(); } catch (serveError) {}
  }

  if (typeof app !== 'undefined' && app.scheduleTask) {
    // scheduleTask evaluates a string in global scope, so the function must be
    // published on the global object first.
    $.global.yimuCraftTick = yimuCraftTick;
    app.scheduleTask('$.global.yimuCraftTick();', 1000, true);
    yimuCraftTick();
  }
})();
`;

fs.mkdirSync(path.join(__dirname, '..', 'src', 'ae-panel'), { recursive: true });
const out = path.join(__dirname, '..', 'src', 'ae-panel', 'ae-state.jsx');
fs.writeFileSync(out, output, 'utf8');
console.log('wrote ' + path.relative(process.cwd(), out) + ' (' + output.length + ' bytes)');
