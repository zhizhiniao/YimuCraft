// Generates the compatibility startup shim. AE work is dispatched on demand.
const fs=require('node:fs'),path=require('node:path');
const output=`// GENERATED by scripts/build-ae-state.cjs. No background project scanning.
(function () {
  // Old releases did not retain their repeating task ID. Neutralize the old
  // callback on hot-load; restarting AE removes the legacy timer completely.
  $.global.yimuCraftTick = function () {};
  if ($.global.yimuCraftStateTaskId !== undefined) {
    try { app.cancelTask($.global.yimuCraftStateTaskId); } catch (error) {}
    delete $.global.yimuCraftStateTaskId;
  }
  $.global.yimuCraftStateMode = 'on-demand-v1';
})();
`;
const out=path.join(__dirname,'..','src','ae-panel','ae-state.jsx');
fs.mkdirSync(path.dirname(out),{recursive:true});fs.writeFileSync(out,output,'utf8');
console.log('wrote '+path.relative(process.cwd(),out)+' (dormant startup shim)');